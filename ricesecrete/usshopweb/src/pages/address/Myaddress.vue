<script setup>
import { onActivated, onMounted, ref } from 'vue';
import Navbar from '@/components/Navbar.vue';
import { useRoute, useRouter } from 'vue-router';
import { UserService } from '@/api/user'
import { CartStore } from '@/store/cart';
import { useUserStore } from '@/store/userStore';
const store = useUserStore();
const router = useRouter()
const route = useRoute()
const cartstore = CartStore()
const dataList = ref([]);
const loadMyAddress = async () => {
    const res = await UserService.addressPage();
    dataList.value = res.dataList;
}

const toEditAddress = (item) => {
    if (route.query.type) {
        if(dataList.value.length > 1){
            cartstore.address = item
        }
        return router.back();
    }
    router.push({ path: '/addaddress', query: { data: JSON.stringify(item) } });
}

const deleteAddress = async (item) => {
    const res = await UserService.addressDelete({ id: item.id });
    loadMyAddress();
    await store.getUserInfo()
}
const showLoading = ref(false);
const addMyAddress = async (item) => {
    showLoading.value = true;
    try {
        showLoading.value = false;
        item.is_default = !item.is_default;
        const res = await UserService.addressSave(item);
        loadMyAddress();
    } catch (error) {
        showLoading.value = false;
    }
}

onActivated(() => {
    loadMyAddress();
})
</script>

